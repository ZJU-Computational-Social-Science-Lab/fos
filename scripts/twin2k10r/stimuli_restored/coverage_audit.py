# This module builds the machine-generated 31/38 coverage audit: one row
# per experiment in the frozen grid with its source, contrast count, and
# status, plus the definitive resolution of the count inconsistency in
# INTEGRATION_REPORT.md (that report says both "35 of 38" and "28 of
# 38"; the frozen registry says 28 — the missing ten contrasts are
# exactly the withheld six's). Nothing here is hand-written output; the
# markdown is rendered from the same rows the tests check, so the
# document can never disagree with the registry. Functions:
#   audit_rows          — the 31 in-grid experiment rows (+2 out-of-grid).
#   audit_resolution    — the before/after counts and the rejected figures.
#   render_audit_markdown — the full audit document as markdown text.
#   write_audit_markdown  — write that document to the checked-in file.
from __future__ import annotations

from pathlib import Path

from twin2k10r.stimuli_restored.registry import (
    coverage_counts,
    merged_registry,
)

AUDIT_DOC = Path(__file__).resolve().parent / "EXPERIMENT_COVERAGE_AUDIT.md"


def audit_rows() -> list[dict]:
    """One audit row per experiment, merged-registry order."""
    return merged_registry()


def audit_resolution() -> dict:
    """The count-resolution facts the audit document states.

    The frozen registry (experiment_registry.csv) holds 38 in-grid
    contrasts; the withheld six hold C-01..C-10, i.e. 10 contrasts, so
    the pre-restoration reachable count is 28 — the "29" proposed by the
    investigation note and the "35" in the report heading are both
    rejected here, with the arithmetic that decides it.
    """
    before = coverage_counts(restored=False)
    after = coverage_counts(restored=True)
    return {
        "grid_experiments": 31,
        "grid_contrasts": 38,
        "pre_restoration_reachable_experiments": before["grid_experiments_reachable"],
        "pre_restoration_reachable_contrasts": before["grid_contrasts_reachable"],
        "pre_restoration_rejected_figures": [29, 35],
        "post_restoration_reachable_experiments": after["grid_experiments_reachable"],
        "post_restoration_reachable_contrasts": after["grid_contrasts_reachable"],
        "withheld_experiments": before["withheld_experiments"],
        "withheld_contrasts": before["withheld_contrasts"],
    }


def _status_text(row: dict) -> str:
    """One row's status cell, including the why when withheld."""
    if row["withheld_reason"]:
        return f"WITHHELD — {row['withheld_reason']}"
    return str(row["status"])


def render_audit_markdown() -> str:
    """The whole audit document, rendered from the same rows as the tests."""
    resolution = audit_resolution()
    lines = [
        "# EXPERIMENT_COVERAGE_AUDIT.md — machine-checked 31/38 coverage",
        "",
        "Generated by `scripts/twin2k10r/stimuli_restored/coverage_audit.py`",
        "from the merged registry and the frozen experiment registry",
        "(experiment_registry.csv). Do not edit by hand — regenerate.",
        "",
        "## Count resolution (INTEGRATION_REPORT.md inconsistency)",
        "",
        "The frozen 31-experiment / 38-contrast grid splits as:",
        "",
        f"- pre-restoration reachable: **{resolution['pre_restoration_reachable_contrasts']} of 38 contrasts**",
        f"  across {resolution['pre_restoration_reachable_experiments']} of 31 experiments;",
        f"- withheld: **{resolution['withheld_experiments']} experiments / {resolution['withheld_contrasts']} contrasts**",
        "  (C-01..C-10 of the frozen registry);",
        f"- post-restoration reachable: **{resolution['post_restoration_reachable_contrasts']} of 38 contrasts**",
        f"  across {resolution['post_restoration_reachable_experiments']} of 31 experiments.",
        "",
        "The figures 29/38 and 35/38 are both rejected: 29 mis-splits the",
        "withheld six as 9 contrasts (C-01..C-10 number ten), and 35 mixes",
        "the report's experiment-denominator confusion into the contrast",
        "count. `28 + 10 = 38` and `25 + 6 = 31` are exact.",
        "",
        "## Per-experiment coverage",
        "",
        "| Experiment | Source | In 31-grid | Contrasts | Status |",
        "|---|---|---|---|---|",
    ]
    for row in audit_rows():
        lines.append(
            f"| {row['name']} | {row['source']} | "
            f"{'yes' if row['in_grid'] else 'no'} | "
            f"{row['n_contrasts']} | {_status_text(row)} |"
        )
    lines += [
        "",
        "Totals: 31 in-grid experiments, 38 in-grid contrasts;",
        "every row READY (nothing remains withheld).",
        "",
    ]
    return "\n".join(lines)


def write_audit_markdown() -> Path:
    """Regenerate the checked-in audit document (the only write path)."""
    AUDIT_DOC.write_text(render_audit_markdown(), encoding="utf-8")
    return AUDIT_DOC
